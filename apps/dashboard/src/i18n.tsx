export type Lang = 'bn' | 'en'
const dicts = { bn, en }
const locales = { bn: 'bn-BD', en: 'en-GB' }

function savedLang(): Lang {
  try {
    return localStorage.getItem('lang') === 'en' ? 'en' : 'bn'
  } catch {
    return 'bn'
  }
}

type Ctx = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: Key, vars?: Record<string, string>) => string
  money: (taka: number) => string
  num: (n: number) => string
  time: (iso: string) => string
  date: (day: Date) => string
}

const LangContext = createContext<Ctx | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState(savedLang)

  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem('lang', lang)
    } catch {}
  }, [lang])

  const value = useMemo<Ctx>(() => {
    const locale = locales[lang]
    const number = new Intl.NumberFormat(locale)
    const date = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' })
    const dayMonth = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', timeZone: 'UTC' })
    return {
      lang,
      setLang,
      t: (key, vars) => dicts[lang][key].replace(/\{(\w+)\}/g, (_, name) => vars?.[name] ?? ''),
      money: (taka) => `৳${number.format(taka)}`,
      num: (n) => number.format(n),
      date: (day) => dayMonth.format(day),
      time: (iso) => {
        const text = date.format(new Date(iso))
        return lang === 'bn' ? text.replace('AM', 'এএম').replace('PM', 'পিএম') : text
      },
    }
  }, [lang])

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang needs LangProvider')
  return ctx
}
